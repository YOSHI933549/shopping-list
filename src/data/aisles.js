function norm(s) {
  return String(s).normalize('NFKC').trim().toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
}

// 正規化済みキーワード -> カテゴリ。同じ語が複数カテゴリにある場合は先に書いたほうを優先。
export const KEYWORDS = (() => {
  const m = new Map();
  for (const [aisle, text] of Object.entries(RAW)) {
    for (const w of text.split(/\s+/).filter(Boolean)) {
      const k = norm(w);
      if (k && !m.has(k)) m.set(k, aisle);
    }
  }
  for (const [w, aisle] of Object.entries(OVERRIDES)) m.set(norm(w), aisle);
  return m;
})();
