describe('categorize', () => {
  it.each(cases)('%s -> %s', (name, aisle) => {
    expect(categorize(name)).toBe(aisle);
  });
  it('ピーマンは「ピー」で誤判定されない', () => expect(categorize('ピーマン')).toBe('野菜・果物'));
  it('たまねぎは卵ではない', () => expect(categorize('たまねぎ')).not.toBe('乳製品・卵'));
  it('すべてのカテゴリが AISLES に存在する', () => {
    for (const a of KEYWORDS.values()) expect(AISLES).toContain(a);
  });
  it('正規化: 全角/半角・カタカナ→ひらがな', () => {
    expect(normalize(' ＡＢＣ ')).toBe('abc');
    expect(normalize('キャベツ')).toBe('きゃべつ');
  });
  it('辞書は数百語ある', () => expect(KEYWORDS.size).toBeGreaterThan(300));
});
